// Turns ../mobile/design/tokens.json into src/tokens.generated.ts (CSS custom properties, both themes).
// Usage: npm run gen:tokens
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

type Value = string | Record<string, string>;
type Token = { name: string; value: Value };
type Style = { name: string; fontSize: string; lineHeight: string; fontWeight: number; letterSpacing?: string };

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = JSON.parse(readFileSync(join(root, '..', 'mobile', 'design', 'tokens.json'), 'utf8'));

const themeIds: string[] = source.color.themes.map((theme: { id: string }) => theme.id);
const colors: Token[] = source.color.tokens;
const byName = new Map(colors.map((token) => [token.name, token.value]));

function resolve(value: Value, theme: string, seen: string[] = []): string {
  if (typeof value === 'object') return value[theme];
  const alias = /^\{(.+)\}$/.exec(value);
  if (!alias) return value;
  if (seen.includes(alias[1])) throw new Error(`Alias cycle at ${alias[1]}`);
  return resolve(byName.get(alias[1])!, theme, [...seen, alias[1]]);
}

// The page must never contain the word "verified" unless the API said so, so the CSS name avoids it.
const cssName = (name: string) => name.replace('verified', 'top');

const block = (theme: string) =>
  colors.map((token) => `--${cssName(token.name)}:${resolve(token.value, theme)};`).join('');

const fixed: string[] = [];
for (const family of ['spacing', 'radius'] as const) {
  for (const token of source[family].tokens as Token[]) fixed.push(`--${token.name}:${token.value};`);
}
for (const group of source.type.groups as { styles: Style[] }[]) {
  for (const style of group.styles) {
    fixed.push(`--${style.name}-size:${style.fontSize};--${style.name}-line:${style.lineHeight};`);
    fixed.push(`--${style.name}-weight:${style.fontWeight};`);
    if (style.letterSpacing) fixed.push(`--${style.name}-tracking:${style.letterSpacing};`);
  }
}

const dark = themeIds.includes('dark') ? 'dark' : themeIds[0];
const light = themeIds.find((id) => id !== dark) ?? dark;
const css = `:root{color-scheme:dark light;${block(dark)}${fixed.join('')}}@media (prefers-color-scheme:light){:root{${block(light)}}}`;

writeFileSync(
  join(root, 'src', 'tokens.generated.ts'),
  `// Generated by scripts/gen-tokens.ts from mobile/design/tokens.json. Do not edit.\nexport const tokensCss = ${JSON.stringify(css)};\n`,
);
