// Turns design/tokens.json into src/shared/design/tokens.generated.ts.
// Usage: node scripts/gen-tokens.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = JSON.parse(readFileSync(join(root, 'design', 'tokens.json'), 'utf8'));

const px = (value) => {
  const match = /^(-?\d+(?:\.\d+)?)px$/.exec(value);
  if (!match) throw new Error(`Expected a px value, got ${value}`);
  return Number(match[1]);
};

// em × fontSize, rounded so 0.06 × 15 is 0.9 and not 0.8999999999999999.
const em = (value, fontSize) => {
  const match = /^(-?\d+(?:\.\d+)?)em$/.exec(value);
  if (!match) throw new Error(`Expected an em value, got ${value}`);
  return Math.round(Number(match[1]) * fontSize * 1e4) / 1e4;
};

const themeIds = source.color.themes.map((theme) => theme.id);

// A token value is a per-theme object, an alias such as "{brand}", or one string for every theme.
function perTheme(tokenList) {
  const byName = new Map(tokenList.map((token) => [token.name, token.value]));
  const resolve = (value, theme, seen = []) => {
    if (typeof value === 'object') return value[theme];
    const alias = /^\{(.+)\}$/.exec(value);
    if (!alias) return value;
    if (seen.includes(alias[1])) throw new Error(`Alias cycle at ${alias[1]}`);
    return resolve(byName.get(alias[1]), theme, [...seen, alias[1]]);
  };
  return Object.fromEntries(
    themeIds.map((theme) => [
      theme,
      Object.fromEntries(tokenList.map((token) => [token.name, resolve(token.value, theme)])),
    ]),
  );
}

const numbers = (tokenList) => Object.fromEntries(tokenList.map((token) => [token.name, px(token.value)]));

const type = {};
for (const group of source.type.groups) {
  for (const style of group.styles) {
    const fontSize = px(style.fontSize);
    type[style.name] = {
      family: group.family,
      fontSize,
      lineHeight: px(style.lineHeight),
      fontWeight: style.fontWeight,
      letterSpacing: style.letterSpacing ? em(style.letterSpacing, fontSize) : 0,
    };
  }
}

const tokens = {
  color: perTheme(source.color.tokens),
  type,
  space: numbers(source.spacing.tokens),
  radius: numbers(source.radius.tokens),
  shadow: perTheme(source.shadow.tokens),
};

const out = `// Generated by scripts/gen-tokens.mjs from design/tokens.json. Do not edit.
export const tokens = ${JSON.stringify(tokens, null, 2)} as const;

export type ThemeId = ${themeIds.map((id) => `'${id}'`).join(' | ')};
export type ColorName = keyof typeof tokens.color.dark;
export type TypeVariant = keyof typeof tokens.type;
`;

writeFileSync(join(root, 'src', 'shared', 'design', 'tokens.generated.ts'), out);
