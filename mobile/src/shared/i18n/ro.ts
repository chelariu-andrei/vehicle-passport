/** The same shape as `en`, with plain strings in place of literals; any key left out is read from `en`. */
type Widen<T> = T extends string
  ? string
  : T extends (...args: infer A) => string
    ? (...args: A) => string
    : T extends readonly unknown[]
      ? T
      : { [K in keyof T]: Widen<T[K]> };
export type DeepPartial<T> = T extends (...args: never[]) => unknown ? T : T extends readonly unknown[] ? T : { [K in keyof T]?: DeepPartial<T[K]> };

